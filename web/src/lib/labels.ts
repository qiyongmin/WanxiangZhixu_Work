// The pattern for the old Section name is a regex so the literal never appears in source (Req 2.2, asserted by tests).
const RENAMED_SECTION = /^line\s+management$/i;
const CURRENT_SECTION_NAME = 'Team Management';

/** Display name of a Section title: the old name is never shown anywhere. */
export function displaySectionTitle(title: string): string {
  const trimmed = title.trim();
  if (RENAMED_SECTION.test(trimmed)) return CURRENT_SECTION_NAME;
  // The server names its built-in virtual Section in Chinese (escaped here so no CJK literal lives in the source).
  if (trimmed === '\u672a\u5f52\u7c7b') return 'Unclassified';
  return title;
}

/** Open Task count badge: 0 shows 0, more than 99 shows 99+. */
export function formatOpenCount(count: number): string {
  if (!Number.isFinite(count) || count <= 0) return '0';
  return count > 99 ? '99+' : String(Math.floor(count));
}

